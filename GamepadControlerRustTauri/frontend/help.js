/* =====================================================================
   help.js —— 独立「使用说明」窗口（WebviewWindow "help-win"），静态渲染。
   ===================================================================== */

// 解构出 getCurrentWindow（用于右上角“关闭”按钮关闭本窗口）
const { getCurrentWindow } = window.__TAURI__.window;

// ---------------------------------------------------------------------
// 工具
// ---------------------------------------------------------------------
// esc：HTML 转义，防止特殊字符破坏页面结构
function esc(s) {
  // 依次替换 & < > " 为对应 HTML 实体
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

// $：按 id 获取 DOM 元素的简写
function $(id) { return document.getElementById(id); }

// ---------------------------------------------------------------------
// 帮助内容
// ---------------------------------------------------------------------
// HELP_SECTIONS：使用说明内容，每项为 [章节标题, 正文]；正文中的 \n 用于换行
const HELP_SECTIONS = [
  ['一、快速上手', // 章节一：快速上手
   '1. 连接手柄，点击「开始映射」。\n' + // 步骤 1
   '2. 默认配置已含一个「默认操作集」，公共层绑定基础按键（A=空格、B=右键、X=左键、Y=I、菜单键=Esc、视图键=M）。\n' + // 步骤 2
   '3. 右摇杆 = 视角控制，左摇杆 = WASD 移动。'], // 步骤 3
  ['二、操作集与层映射', // 章节二：操作集与层映射
   '操作集是最高层容器，每个操作集内包含 1 个公共层 + 最多 10 个操作层。\n' + // 容器结构说明
   '切换操作集时，其下所有层整体切换（适合不同游戏/场景一键切换整套配置）。\n' + // 切换行为
   '• 添加：新建空操作集（默认名可再改）。\n' + // 添加操作
   '• 复制：把当前操作集整体复制为新操作集，可直接改名。\n' + // 复制操作
   '• 重命名：修改当前操作集的自定义名字。\n' + // 重命名操作
   '• 删除：至少保留一个操作集。\n' + // 删除操作与限制
   '悬浮窗始终显示当前操作集名称。'], // 悬浮窗联动
  ['三、层切换机制', // 章节三：层切换机制
   '操作层由公共层的「切层」(SwitchLayer) 映射驱动：按住切层键激活目标层，松开自动回退。\n' + // 切层机制
   '按键查询顺序：最后激活的操作层 → 较早的操作层 → 公共层（兜底）。'], // 查询顺序
  ['四、悬浮窗', // 章节四：悬浮窗
   '「显示悬浮窗」打开置顶透明信息窗，实时显示：当前操作集、当前层、连接状态、按下的手柄按键。\n' + // 悬浮窗内容
   '收起时为一个迷你圆角矩形（连接圆点 + 当前层名，锁定状态看边框颜色）：单击展开。'], // 收起态操作
  ['五、配置文件', // 章节五：配置文件
   '配置文件 steamlike_config.json 位于程序同目录，绿色便携。与安卓版格式兼容（version=2）。'], // 配置说明
];

// ---------------------------------------------------------------------
// 渲染 + 绑定
// ---------------------------------------------------------------------
// renderHelp：把帮助章节渲染进页面
function renderHelp() {
  $('help-sections').innerHTML = HELP_SECTIONS.map(([title, body]) => // 遍历每个章节生成卡片
    '<div class="help-section">' + // 章节卡片容器
    '<div class="help-section-title">' + esc(title) + '</div>' + // 章节标题
    '<div class="help-section-body">' + esc(body) + '</div>' + // 章节正文（转义后保留换行）
    '</div>'
  ).join('');
}

$('help-close').addEventListener('click', () => getCurrentWindow().close()); // 右上角“关闭”按钮：关闭本窗口

renderHelp(); // 页面加载后渲染使用说明内容

// ---------------------------------------------------------------------
// 窗口显示策略：
//   - 带 ?prewarm=1（应用启动时预热创建）：保持隐藏，用户点击后由 main.js 调用 show() 显示
//   - 不带 prewarm（用户点击后才新建）：渲染完成后自动显示，避免打开瞬间白屏闪动
// ---------------------------------------------------------------------
if (!new URLSearchParams(location.search).has('prewarm')) { // 非预热窗口才自动显示
  requestAnimationFrame(() => getCurrentWindow().show()); // 下一帧绘制后显示窗口，杜绝白屏
  setTimeout(() => getCurrentWindow().show(), 1500); // 兜底：确保窗口最终可见
}
